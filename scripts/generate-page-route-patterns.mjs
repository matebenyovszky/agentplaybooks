import { readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const files = await readdir(resolve(root, "src/app"), { recursive: true });
const paths = files.map(file => file.replaceAll("\\", "/"))
  .filter(file => /(?:^|\/)page\.(?:tsx?|jsx?)$/.test(file))
  .map(file => file.split("/").slice(0, -1).filter(segment => !/^\(.*\)$/.test(segment) && !segment.startsWith("@")))
  .sort((a, b) => a.join("/").localeCompare(b.join("/")));
const metadata = files.map(file => file.replaceAll("\\", "/"))
  .filter(file => /(?:^|\/)(?:robots|sitemap|manifest)\.(?:tsx?|jsx?)$/.test(file))
  .map(file => `/${file.replace(/\.(?:tsx?|jsx?)$/, "").replace(/robots$/, "robots.txt").replace(/sitemap$/, "sitemap.xml").replace(/manifest$/, "manifest.webmanifest")}`);
// Reserve unsupported advanced route conventions rather than risk false 404s.
if (files.some(file => /(?:^|[\\/])(?:@|\(\.)/.test(file))) throw Error("Review advanced page routes before enabling native 404 dispatch.");
await writeFile(resolve(root, "src/worker/page-route-patterns.ts"),
  `// Generated by scripts/generate-page-route-patterns.mjs. Do not edit.\n`
  + `export const pageRoutePatterns: string[][] = ${JSON.stringify(paths, null, 2)};\n`
  + `export const metadataRoutePaths = new Set<string>(${JSON.stringify(metadata)});\n`);
