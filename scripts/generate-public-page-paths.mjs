import { readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const paths = ["/", "/docs", "/docs/readme", "/blog", "/enterprise", "/privacy", "/terms"];
for (const section of ["docs", "blog"]) {
  for (const file of await readdir(resolve(root, "public", section))) {
    // Only deployment-owned public Markdown documents qualify. Unknown slugs,
    // nested routes, static assets, and future private pages are not admitted.
    if (!file.endsWith(".md")) continue;
    const slug = file.slice(0, -3).replace(/\.(?:en|hu|de|es)$/, "");
    if (/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) paths.push(`/${section}/${slug}`);
  }
}
const unique = [...new Set(paths)].sort();
await writeFile(resolve(root, "src/worker/public-page-paths.ts"),
  `// Generated by scripts/generate-public-page-paths.mjs. Do not edit.\n`
  + `// These pages render public build assets and locale only; no session data.\n`
  + `export const publicPagePaths = new Set<string>(${JSON.stringify(unique, null, 2)});\n`);
