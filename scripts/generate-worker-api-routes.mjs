import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const files = (await Promise.all(["api", ".well-known", "playbooks"].map(async (base) => {
  const directory = resolve(root, "src/app", base);
  return (await readdir(directory, { recursive: true }))
    .filter((file) => file.replaceAll("\\", "/").endsWith("/route.ts") || file === "route.ts")
    .map((file) => ({ base, directory, file }));
}))).flat();
const routes = await Promise.all(files.map(async ({ base, directory, file }) => {
  const source = await readFile(resolve(directory, file), "utf8");
  const segments = relative(directory, dirname(resolve(directory, file))).replaceAll("\\", "/").split("/");
  // Only native Request/Hono handlers are eligible. Next-specific handlers
  // remain explicit reservations so the optional catch-all cannot shadow them.
  const direct = !/from\s+["']next\//.test(source)
    && (source.includes("// @worker-native") || /from\s+["']hono\/vercel["']/.test(source) || /export async function POST\(request: Request, context: RouteContext\)/.test(source));
  let methods = [...source.matchAll(/export\s+(?:(?:async\s+)?function|const)\s+(GET|POST|PUT|PATCH|DELETE|OPTIONS|HEAD)\b/g)].map((match) => match[1]);
  // The config test endpoint intentionally re-exports its parent's Hono POST.
  if (base === "api" && file.replaceAll("\\", "/") === "mcp/config/[serverId]/test/route.ts") methods = ["POST"];
  return { basePath: `/${base}`, segments, direct, methods, module: `../app/${base}/${file.replaceAll("\\", "/").replace(/\.ts$/, "")}` };
}));
routes.sort((left, right) => {
  for (let index = 0; index < Math.max(left.segments.length, right.segments.length); index++) {
    const weight = (segment) => !segment ? 0 : segment.startsWith("[[...") ? -1 : segment.startsWith("[...") ? 1 : segment.startsWith("[") ? 2 : 3;
    const difference = weight(right.segments[index]) - weight(left.segments[index]);
    if (difference) return difference;
    if (left.segments[index] !== right.segments[index]) return (left.segments[index] ?? "").localeCompare(right.segments[index] ?? "");
  }
  return 0;
});
const rows = routes.map((route) => {
  return `  { basePath: ${JSON.stringify(route.basePath)}, segments: ${JSON.stringify(route.segments)}, methods: ${JSON.stringify(route.methods)}, handlers: ${route.direct ? `() => import(${JSON.stringify(route.module)}) as unknown as Promise<ApiHandlers>` : "null"} },`;
});
const output = `// Generated by scripts/generate-worker-api-routes.mjs. Do not edit.\nimport type { ApiHandlers, ApiRoute } from "./api-dispatch";\n\nexport const apiRoutes: ApiRoute[] = [\n${rows.join("\n")}\n];\n`;
await writeFile(resolve(root, "src/worker/api-routes.ts"), output);
