import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const api = resolve(root, "src/app/api");
const files = (await readdir(api, { recursive: true })).filter((file) => file.replaceAll("\\", "/").endsWith("/route.ts") || file === "route.ts");
const routes = await Promise.all(files.map(async (file) => {
  const source = await readFile(resolve(api, file), "utf8");
  const segments = relative(api, dirname(resolve(api, file))).replaceAll("\\", "/").split("/");
  // Only native Request/Hono handlers are eligible. Next-specific handlers
  // remain explicit reservations so the optional catch-all cannot shadow them.
  const direct = !/from\s+["']next\//.test(source)
    && (/from\s+["']hono\/vercel["']/.test(source) || /export async function POST\(request: Request, context: RouteContext\)/.test(source));
  const methods = [...source.matchAll(/export\s+(?:(?:async\s+)?function|const)\s+(GET|POST|PUT|PATCH|DELETE|OPTIONS|HEAD)\b/g)].map((match) => match[1]);
  return { segments, direct, methods, module: `../app/api/${file.replaceAll("\\", "/").replace(/\.ts$/, "")}` };
}));
routes.sort((left, right) => {
  for (let index = 0; index < Math.max(left.segments.length, right.segments.length); index++) {
    const weight = (segment) => !segment ? 0 : segment.startsWith("[[...") ? -1 : segment.startsWith("[...") ? 1 : segment.startsWith("[") ? 2 : 3;
    const difference = weight(right.segments[index]) - weight(left.segments[index]);
    if (difference) return difference;
    if (left.segments[index] !== right.segments[index]) return (left.segments[index] ?? "").localeCompare(right.segments[index] ?? "");
  }
  return 0;
});
let imports = "";
const rows = routes.map((route, index) => {
  if (route.direct) imports += `import * as route${index} from ${JSON.stringify(route.module)};\n`;
  return `  { segments: ${JSON.stringify(route.segments)}, methods: ${JSON.stringify(route.methods)}, handlers: ${route.direct ? `route${index} as unknown as ApiHandlers` : "null"} },`;
});
const output = `// Generated by scripts/generate-worker-api-routes.mjs. Do not edit.\nimport type { ApiHandlers, ApiRoute } from "./api-dispatch";\n${imports}\nexport const apiRoutes: ApiRoute[] = [\n${rows.join("\n")}\n];\n`;
await writeFile(resolve(root, "src/worker/api-routes.ts"), output);
