/**
 * A playbook as a Hermes Agent profile distribution — one bot, one playbook.
 *
 * Hermes already knows how to install and update a bot from a directory or a
 * git URL: `hermes profile install <source> --name <bot>` creates a profile,
 * and `hermes profile update <bot>` re-pulls it, replacing what the
 * distribution owns and leaving the bot's own sessions, memories and history
 * alone. That is the whole delivery mechanism, so this writes the layout Hermes
 * expects rather than reimplementing any of it:
 *
 *     distribution.yaml   the manifest: name, version, what it owns
 *     SOUL.md             the persona, which Hermes loads as slot #1
 *     skills/<name>/      SKILL.md and the files each skill bundles
 *
 * Two things are deliberately absent.
 *
 * **No `config.yaml`.** `hermes profile install` replaces that file wholesale
 * rather than merging it, so shipping one would hand the bot whichever model
 * and providers happened to be right when the distribution was built, and
 * overwrite the ones the machine is actually configured for. Which model a bot
 * runs is the operator's decision.
 *
 * That leaves a gap worth knowing about: unlike `hermes profile create`,
 * `profile install` copies no config at all, so a freshly installed bot has no
 * providers and no model and cannot answer anything. Closing it is the second
 * command, `apb sync --target=hermes --profile=<bot> --apply`, which seeds the
 * bot's config from the installation's own and merges the playbook's MCP
 * servers into it. The model can be changed per bot afterwards.
 *
 * **No `cron/`.** A playbook has no schedule to express yet. The directory is
 * distribution-owned by default in Hermes, so adding one later needs no change
 * here beyond writing it.
 */
import { mkdir, readFile, readdir, rename, writeFile } from "node:fs/promises";
import path from "node:path";

import { normalizeText } from "./discovery.js";
import { readLink } from "./remote.js";

/** Where `pull` puts each piece, and therefore where this reads them from. */
const PORTABLE_SKILLS_DIR = ".agents/skills";
const PORTABLE_PERSONA_PATH = ".agents/persona.md";

/** Hermes reads the manifest under this name and no other. */
export const MANIFEST_FILENAME = "distribution.yaml";

/**
 * Versions of Hermes that understand profile distributions. `profile install`
 * refuses a manifest that asks for more than the installed CLI provides, which
 * is a clearer failure than a half-installed bot.
 */
const HERMES_REQUIRES = ">=0.20.0";

const SKILL_FILE_DIRECTORIES = ["scripts", "references", "assets", "examples", "templates"];
const SAFE_PROFILE_NAME = /^[a-z0-9](?:[a-z0-9_-]{0,62}[a-z0-9])?$/;

async function readIfExists(absolutePath) {
  try {
    return normalizeText(await readFile(absolutePath, "utf8"));
  } catch (error) {
    if (error?.code === "ENOENT") return null;
    throw error;
  }
}

/** YAML for the handful of scalar shapes a manifest actually contains. */
function yamlScalar(value) {
  const text = String(value);
  return /^[A-Za-z0-9][A-Za-z0-9 ._\-/:]*$/.test(text) && !/:\s/.test(text)
    ? text
    : JSON.stringify(text);
}

function renderManifest({ name, version, description, author, owned }) {
  const lines = [
    "# Generated by `agentplaybooks export hermes`. Edit the playbook, not this file.",
    `name: ${yamlScalar(name)}`,
    `version: ${yamlScalar(version)}`,
  ];
  if (description) lines.push(`description: ${yamlScalar(description)}`);
  if (author) lines.push(`author: ${yamlScalar(author)}`);
  lines.push(`hermes_requires: ${yamlScalar(HERMES_REQUIRES)}`);
  lines.push("");
  lines.push("# Replaced on every `hermes profile update`. Everything else in the profile");
  lines.push("# -- sessions, memories, state.db, .env, logs -- belongs to the user and is");
  lines.push("# never touched, so a bot can be updated without losing what it remembers.");
  lines.push("#");
  lines.push("# config.yaml is deliberately not listed: `profile install` replaces that file");
  lines.push("# rather than merging it, so shipping one would pin the bot's model and");
  lines.push("# providers to whatever was true when this was exported.");
  lines.push("distribution_owned:");
  for (const entry of owned) lines.push(`  - ${entry}`);
  return `${lines.join("\n")}\n`;
}

/**
 * The skills in a pulled project: every directory under `.agents/skills` that
 * holds a `SKILL.md`, with the files it bundles.
 */
async function readPortableSkills(root) {
  const skillsRoot = path.join(root, ...PORTABLE_SKILLS_DIR.split("/"));
  const entries = await readdir(skillsRoot, { withFileTypes: true }).catch(() => []);
  const skills = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const directory = path.join(skillsRoot, entry.name);
    const document = await readIfExists(path.join(directory, "SKILL.md"));
    if (document === null) continue;

    const files = [{ relativePath: "SKILL.md", content: document }];
    const inside = await readdir(directory, { withFileTypes: true }).catch(() => []);
    for (const child of inside) {
      if (child.isFile() && child.name !== "SKILL.md") {
        const content = await readIfExists(path.join(directory, child.name));
        if (content !== null) files.push({ relativePath: child.name, content });
      } else if (child.isDirectory() && SKILL_FILE_DIRECTORIES.includes(child.name)) {
        const nested = await readdir(path.join(directory, child.name), { withFileTypes: true }).catch(() => []);
        for (const file of nested) {
          if (!file.isFile()) continue;
          const content = await readIfExists(path.join(directory, child.name, file.name));
          if (content !== null) files.push({ relativePath: `${child.name}/${file.name}`, content });
        }
      }
    }
    files.sort((a, b) => a.relativePath.localeCompare(b.relativePath));
    skills.push({ name: entry.name, files });
  }

  skills.sort((a, b) => a.name.localeCompare(b.name));
  return skills;
}

/**
 * Plan the distribution directory for the playbook this project is linked to.
 *
 * Nothing is written and nothing is fetched: the source is what `pull` already
 * put on disk, so the same project produces the same distribution whether or
 * not the machine is online.
 */
export async function planHermesExport(root, destination, { name, version } = {}) {
  const link = await readLink(root);
  const profileName = (name ?? link?.name ?? path.basename(root))
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  if (!SAFE_PROFILE_NAME.test(profileName)) {
    throw new Error(`'${profileName}' is not a usable Hermes profile name. Pass --name with a lowercase, hyphenated one.`);
  }

  const skills = await readPortableSkills(root);
  const persona = await readIfExists(path.join(root, ...PORTABLE_PERSONA_PATH.split("/")));

  if (skills.length === 0 && persona === null) {
    throw new Error(`Nothing to export: ${root} has no ${PORTABLE_SKILLS_DIR} and no ${PORTABLE_PERSONA_PATH}. Run 'agentplaybooks pull <playbook> --apply' first.`);
  }

  const files = [];
  if (persona !== null && persona.trim().length > 0) {
    files.push({ path: "SOUL.md", content: persona.endsWith("\n") ? persona : `${persona}\n` });
  }
  for (const skill of skills) {
    for (const file of skill.files) {
      files.push({
        path: `skills/${skill.name}/${file.relativePath}`,
        content: file.content.endsWith("\n") ? file.content : `${file.content}\n`,
      });
    }
  }

  // Only what is actually shipped is declared owned. Naming SOUL.md in a
  // distribution that has no persona would make `profile update` delete the
  // one the user wrote.
  const owned = [MANIFEST_FILENAME];
  if (files.some((file) => file.path === "SOUL.md")) owned.push("SOUL.md");
  if (skills.length > 0) owned.push("skills/");

  files.unshift({
    path: MANIFEST_FILENAME,
    content: renderManifest({
      name: profileName,
      version: version ?? "0.1.0",
      description: link?.name ? `Hermes profile generated from the '${link.name}' playbook` : null,
      author: null,
      owned,
    }),
  });

  return {
    root,
    destination: path.resolve(destination),
    profileName,
    playbook: link ? { guid: link.guid, name: link.name } : null,
    skills: skills.map((skill) => skill.name),
    files,
  };
}

/**
 * Write the planned distribution. Each file goes out through a temporary name
 * in its own directory, so an interrupted export leaves the previous
 * distribution intact rather than a half-written one Hermes would install.
 */
export async function applyHermesExport(plan) {
  const written = [];
  for (const file of plan.files) {
    const absolutePath = path.join(plan.destination, ...file.path.split("/"));
    await mkdir(path.dirname(absolutePath), { recursive: true });
    const temporary = path.join(
      path.dirname(absolutePath),
      `.${path.basename(absolutePath)}.${process.pid}.tmp`,
    );
    await writeFile(temporary, file.content, "utf8");
    await rename(temporary, absolutePath);
    written.push(file.path);
  }
  return { written };
}

export function printHermesExportPlan(plan) {
  console.log(`Hermes profile '${plan.profileName}' from ${plan.playbook?.name ?? "this project"}:`);
  for (const file of plan.files) console.log(`  write ${file.path}`);
  if (plan.skills.length > 0) console.log(`  ${plan.skills.length} skill(s): ${plan.skills.join(", ")}`);
}

/** What to run once the directory exists. Printed rather than executed: */
export function hermesInstallHint(plan) {
  return [
    `  hermes profile install ${plan.destination} --name ${plan.profileName}`,
    `  agentplaybooks sync --target=hermes --profile=${plan.profileName} --apply   # MCP servers, model`,
    "",
    `Later, to take an update: re-run 'pull' and 'export hermes', then`,
    `  hermes profile update ${plan.profileName}`,
  ].join("\n");
}
